def جملة_لأرقام(جملة, مفردات):
    متجه = np.zeros(len(مفردات))
    كلمات = جملة.split()
    for كلمة in كلمات:
        if كلمة in مفردات:
            متجه[مفردات[كلمة]] = 1
    return متجه

كل_الكلمات = []
for جملة, _ in بيانات_تدريب:
    كل_الكلمات.extend(جملة.split())
مفردات = {كلمة: i for i, كلمة in enumerate(set(كل_الكلمات))}

X = np.array([جملة_لأرقام(ج, مفردات) for ج, _ in بيانات_تدريب])
y = [تصنيف for _, تصنيف in بيانات_تدريب]

نموذج = MLPClassifier(
    hidden_layer_sizes=(256, 128, 64),
    max_iter=2000,
    random_state=42
)
نموذج.fit(X, y)

with open('model.pkl', 'wb') as f:
    pickle.dump((نموذج, مفردات), f)

print("تم تدريب النموذج! ✅")
print(f"عدد الجمل: {len(بيانات_تدريب)}")
print(f"عدد التصنيفات: {len(set(y))}")
print(f"دقة التدريب: {نموذج.score(X, y)*100:.1f}%")