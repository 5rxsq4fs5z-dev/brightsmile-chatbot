def فهم_الكلمة(كلمة, قائمة):
    if كلمة in قائمة:
        return True
    مشابه = get_close_matches(كلمة, قائمة, n=1, cutoff=0.75)
    return len(مشابه) > 0

def فهم_النية(جملة):
    كلمات = word_tokenize(جملة)
    كلمات_مهمة = [ك for ك in كلمات if ك not in كلمات_زايدة]

    لديه_حجز = any(فهم_الكلمة(ك, كلمات_حجز) for ك in كلمات_مهمة)
    لديه_فعل_حجز = any(فهم_الكلمة(ك, كلمات_افعال_حجز) for ك in كلمات_مهمة)
    لديه_علاج = any(فهم_الكلمة(ك, كلمات_علاج) for ك in كلمات_مهمة)
    لديه_كشف = any(فهم_الكلمة(ك, كلمات_كشف) for ك in كلمات_مهمة)
    لديه_سعر = any(فهم_الكلمة(ك, كلمات_سعر) for ك in كلمات_مهمة)
    لديه_عروض = any(فهم_الكلمة(ك, كلمات_عروض) for ك in كلمات_مهمة)
    لديه_موقع = any(فهم_الكلمة(ك, كلمات_موقع) for ك in كلمات_مهمة)
    لديه_وقت = any(فهم_الكلمة(ك, كلمات_وقت) for ك in كلمات_مهمة)
    لديه_مشكلة = any(فهم_الكلمة(ك, كلمات_مشكلة) for ك in كلمات_مهمة)
    لديه_الغاء = any(فهم_الكلمة(ك, كلمات_الغاء) for ك in كلمات_مهمة)
    لديه_طوارئ = any(فهم_الكلمة(ك, كلمات_طوارئ) for ك in كلمات_مهمة)
    لديه_ترحيب = any(فهم_الكلمة(ك, كلمات_ترحيب) for ك in كلمات_مهمة)
    لديه_دكتور = any(فهم_الكلمة(ك, كلمات_دكتور) for ك in كلمات_مهمة)
    لديه_تواصل = any(فهم_الكلمة(ك, كلمات_تواصل) for ك in كلمات_مهمة)

    if لديه_طوارئ and not لديه_حجز and not لديه_وقت and not لديه_دكتور:
        return "طوارئ"
    elif لديه_ترحيب and not لديه_حجز and not لديه_سعر and not لديه_علاج and not لديه_دكتور:
        return "ترحيب"
    elif لديه_الغاء and not لديه_حجز:
        return "إلغاء موعد"
    elif لديه_عروض and not لديه_حجز:
        return "سؤال عن العروض"
    elif لديه_تواصل and not لديه_فعل_حجز and not (لديه_حجز and not لديه_تواصل):
        return "سؤال عن التواصل"
    elif لديه_موقع and not لديه_حجز:
        return "سؤال عن الموقع"
    elif لديه_وقت and not لديه_حجز:
        return "سؤال عن الدوام"
    elif لديه_فعل_حجز or (لديه_حجز and (لديه_علاج or لديه_كشف or لديه_مشكلة)):
        return "حجز موعد"
    elif لديه_سعر or (لديه_علاج and not لديه_حجز):
        return "سؤال عن السعر"
    elif لديه_كشف and not لديه_حجز:
        return "سؤال عن السعر"
    elif لديه_مشكلة and not لديه_حجز and not لديه_سعر:
        return "سؤال عن مشكلة"
    elif لديه_دكتور and not لديه_حجز:
        return "سؤال عن طبيب"
    elif لديه_حجز and not لديه_تواصل:
        return "حجز موعد"
    else:
        return "غير معروف"

