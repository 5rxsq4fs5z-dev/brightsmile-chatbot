class ذاكرة_المحادثة:
    def __init__(self):
        self.ذاكرة = deque(maxlen=10)
        self.اسم_المريض = None
        self.آخر_موضوع = None
        self.مرحلة_الحجز = None
        self.يوم_الحجز = None
        self.وقت_الحجز = None
        self.خدمة_الحجز = "كشف"
        self.جوال_المريض = None

    def استخرج_الاسم(self, رسالة):
        أنماط = [
            r'اسمي\s+(\w+)',
            r'أنا\s+(\w+)',
            r'انا\s+(\w+)',
            r'أسمي\s+(\w+)',
        ]
        for نمط in أنماط:
            نتيجة = re.search(نمط, رسالة)
            if نتيجة:
                self.اسم_المريض = نتيجة.group(1)
                return self.اسم_المريض
        return None

    def خصص_الرد(self, رد, نية):
        self.آخر_موضوع = نية
        if self.اسم_المريض:
            if نية == "طوارئ":
                return f"سلامتك {self.اسم_المريض}! اتصل علينا فوراً على 0501234567."
            elif نية == "ترحيب":
                return f"أهلاً {self.اسم_المريض}! كيف أقدر أساعدك اليوم؟"
        return رد

def جملة_لأرقام(جملة, مفردات):
    متجه = np.zeros(len(مفردات))
    كلمات = جملة.split()
    for كلمة in كلمات:
        if كلمة in مفردات:
            متجه[مفردات[كلمة]] = 1
    return متجه

def هل_رقم_جوال(نص):
    نص_نظيف = re.sub(r'\s+', '', نص)
    return bool(re.match(r'^[0-9+]{9,13}$', نص_نظيف))

def استخرج_اليوم(رسالة):
    for يوم in أيام_الأسبوع:
        if يوم in رسالة:
            return يوم
    if "بكره" in رسالة or "بكرة" in رسالة:
        return "غداً"
    if "اليوم" in رسالة:
        return "اليوم"
    return None

def استخرج_الوقت(رسالة):
    for وقت in أوقات_متاحة:
        if وقت.split(":")[0] in رسالة:
            return وقت
    return None

def فهم_النية(جملة):
    # تحقق من الأزرار أولاً
    خريطة_الأزرار = {
        "📅 حجز موعد": "حجز موعد",
        "❌ إلغاء موعد": "إلغاء موعد",
        "💰 الأسعار": "سؤال عن السعر",
        "🏥 التأمين": "سؤال عن التأمين",
        "👨‍⚕️ الأطباء": "سؤال عن طبيب",
        "🕐 الدوام": "سؤال عن الدوام",
        "📍 الموقع": "سؤال عن الموقع",
        "📞 التواصل": "سؤال عن التواصل",
        "🎁 العروض": "سؤال عن العروض",
    }
    if جملة in خريطة_الأزرار:
        return خريطة_الأزرار[جملة]

    تحيات = ['السلام', 'عليكم', 'وعليكم', 'مرحبا', 'هلا', 'اهلا',
              'صباح', 'مساء', 'هاي', 'هلو', 'اهلين', 'يهلا', 'حياك']
    كلمات_جملة = جملة.split()
    if any(ك in تحيات for ك in كلمات_جملة):
        return "ترحيب"

    متجه = جملة_لأرقام(جملة, مفردات)
    تصنيف = نموذج.predict([متجه])[0]
    ثقة = نموذج.predict_proba([متجه]).max()
    if ثقة < 0.4:
        return "غير معروف"
    return تصنيف

def رد_البوت(نية, رسالة=""):
    رسالة_lower = رسالة.strip()
    if نية == "ترحيب":
        if "صباح الخير" in رسالة_lower:
            return random.choice(ردود_متنوعة["ترحيب"]["صباح الخير"])
        elif "مساء الخير" in رسالة_lower:
            return random.choice(ردود_متنوعة["ترحيب"]["مساء الخير"])
        elif "السلام عليكم ورحمة الله وبركاته" in رسالة_lower:
            return random.choice(ردود_متنوعة["ترحيب"]["السلام عليكم ورحمة الله وبركاته"])
        elif "السلام" in رسالة_lower:
            return random.choice(ردود_متنوعة["ترحيب"]["السلام عليكم"])
        elif any(k in رسالة_lower for k in ["شكرا", "شكراً", "مشكور", "يسلمو", "تسلمون", "يعطيك"]):
            return random.choice(ردود_متنوعة["ترحيب"]["شكرا"])
        elif any(k in رسالة_lower for k in ["باي", "مع السلامة", "وداع"]):
            return random.choice(ردود_متنوعة["ترحيب"]["باي"])
        else:
            return random.choice(ردود_متنوعة["ترحيب"]["default"])
    elif نية in ردود_متنوعة:
        ردود = ردود_متنوعة[نية]
        if isinstance(ردود, list):
            return random.choice(ردود)
        return ردود
    return random.choice(ردود_متنوعة["غير معروف"])

async def handle_message(update: Update, context: ContextTypes.DEFAULT_TYPE):
    رسالة = update.message.text
    معرف = update.message.from_user.id

    if معرف not in ذاكرة_المستخدمين:
        ذاكرة_المستخدمين[معرف] = ذاكرة_المحادثة()

    ذاكرة = ذاكرة_المستخدمين[معرف]
    ذاكرة.استخرج_الاسم(رسالة)

    # ========== مرحلة الاسم ==========
    if ذاكرة.مرحلة_الحجز == "انتظار_الاسم":
        ذاكرة.اسم_المريض = رسالة.strip()
        ذاكرة.مرحلة_الحجز = "انتظار_الخدمة"
        لوحة = ReplyKeyboardMarkup(
            [خدمات_متاحة[:3], خدمات_متاحة[3:6], خدمات_متاحة[6:]],
            resize_keyboard=True, one_time_keyboard=True
        )
        await update.message.reply_text(
            f"أهلاً {ذاكرة.اسم_المريض}! وش الخدمة اللي تحتاجها؟",
            reply_markup=لوحة
        )
        return

    # ========== مرحلة الخدمة ==========
    elif ذاكرة.مرحلة_الحجز == "انتظار_الخدمة":
        ذاكرة.خدمة_الحجز = رسالة.strip()
        ذاكرة.مرحلة_الحجز = "انتظار_اليوم"
        لوحة = ReplyKeyboardMarkup(
            [أيام_الأسبوع[:3], أيام_الأسبوع[3:]],
            resize_keyboard=True, one_time_keyboard=True
        )
        await update.message.reply_text(
            "ممتاز! وش اليوم المناسب لك؟",
            reply_markup=لوحة
        )
        return

    # ========== مرحلة اليوم ==========
    elif ذاكرة.مرحلة_الحجز == "انتظار_اليوم":
        يوم = استخرج_اليوم(رسالة)
        if يوم:
            ذاكرة.يوم_الحجز = يوم
            ذاكرة.مرحلة_الحجز = "انتظار_الوقت"
            لوحة = ReplyKeyboardMarkup(
                [أوقات_متاحة[:4], أوقات_متاحة[4:8], أوقات_متاحة[8:]],
                resize_keyboard=True, one_time_keyboard=True
            )
            await update.message.reply_text(
                f"المواعيد المتاحة يوم {يوم}:",
                reply_markup=لوحة
            )
            return
        else:
            await update.message.reply_text("اختر من الأزرار أو اكتب اليوم مثلاً: السبت، الأحد...")
            return

    # ========== مرحلة الوقت ==========
    elif ذاكرة.مرحلة_الحجز == "انتظار_الوقت":
        وقت = استخرج_الوقت(رسالة)
        if وقت:
            ذاكرة.وقت_الحجز = وقت
            ذاكرة.مرحلة_الحجز = "انتظار_الجوال"
            await update.message.reply_text(
                f"ممتاز! موعدك:\nالخدمة: {ذاكرة.خدمة_الحجز}\nاليوم: {ذاكرة.يوم_الحجز}\nالوقت: {وقت}\n\nأخير، عطني رقم جوالك للتأكيد.",
                reply_markup=ReplyKeyboardRemove()
            )
            return
        else:
            await update.message.reply_text("اختر من الأزرار أو اكتب الساعة مثلاً: 9 أو 10...")
            return

    # ========== مرحلة الجوال ==========
    elif ذاكرة.مرحلة_الحجز == "انتظار_الجوال":
        if هل_رقم_جوال(رسالة):
            ذاكرة.جوال_المريض = رسالة
            اسم = ذاكرة.اسم_المريض or "غير محدد"
            حفظ_حجز(اسم, رسالة, ذاكرة.يوم_الحجز, ذاكرة.وقت_الحجز, ذاكرة.خدمة_الحجز)
            ذاكرة.مرحلة_الحجز = None
            await update.message.reply_text(
                f"تم الحجز بنجاح!\n"
                f"الاسم: {اسم}\n"
                f"الخدمة: {ذاكرة.خدمة_الحجز}\n"
                f"اليوم: {ذاكرة.يوم_الحجز}\n"
                f"الوقت: {ذاكرة.وقت_الحجز}\n"
                f"الجوال: {رسالة}\n\n"
                f"سنتواصل معك لتأكيد الموعد. نتمنى لك يوماً سعيداً!",
                reply_markup=القائمة_الرئيسية
            )
            return
        else:
            await update.message.reply_text("الرقم ما صح. أعد إدخال رقم الجوال.")
            return

    # ========== مرحلة خيار الإلغاء ==========
    elif ذاكرة.مرحلة_الحجز == "انتظار_خيار_إلغاء":
        if "١" in رسالة or "نهائي" in رسالة or "الغ" in رسالة:
            ذاكرة.مرحلة_الحجز = "انتظار_جوال_إلغاء_نهائي"
            await update.message.reply_text(
                "عطني رقم جوالك للتأكيد.",
                reply_markup=ReplyKeyboardRemove()
            )
        elif "٢" in رسالة or "غير" in رسالة or "تغيير" in رسالة:
            ذاكرة.مرحلة_الحجز = "انتظار_جوال_تغيير"
            await update.message.reply_text(
                "عطني رقم جوالك للتأكيد.",
                reply_markup=ReplyKeyboardRemove()
            )
        else:
            await update.message.reply_text("اختر ١ للإلغاء النهائي أو ٢ لتغيير الموعد.")
        return

    # ========== إلغاء نهائي ==========
    elif ذاكرة.مرحلة_الحجز == "انتظار_جوال_إلغاء_نهائي":
        if هل_رقم_جوال(رسالة):
            إلغاء_حجز(رسالة)
            ذاكرة.مرحلة_الحجز = None
            await update.message.reply_text(
                "تم إلغاء موعدك بنجاح.\nيسعدنا نشوفك في وقت ثاني!",
                reply_markup=القائمة_الرئيسية
            )
            return
        else:
            await update.message.reply_text("الرقم ما صح. أعد المحاولة.")
            return

    # ========== تغيير الموعد ==========
    elif ذاكرة.مرحلة_الحجز == "انتظار_جوال_تغيير":
        if هل_رقم_جوال(رسالة):
            إلغاء_حجز(رسالة)
            ذاكرة.مرحلة_الحجز = "انتظار_اليوم"
            لوحة = ReplyKeyboardMarkup(
                [أيام_الأسبوع[:3], أيام_الأسبوع[3:]],
                resize_keyboard=True, one_time_keyboard=True
            )
            await update.message.reply_text(
                "تم إلغاء موعدك القديم. وش اليوم الجديد؟",
                reply_markup=لوحة
            )
            return
        else:
            await update.message.reply_text("الرقم ما صح. أعد المحاولة.")
            return

    # ========== المنطق الأساسي ==========
    نية = فهم_النية(رسالة)

    if نية == "حجز موعد":
        if not ذاكرة.اسم_المريض:
            ذاكرة.مرحلة_الحجز = "انتظار_الاسم"
            await update.message.reply_text(
                "بكل سرور! ما اسمك الكريم؟",
                reply_markup=ReplyKeyboardRemove()
            )
        else:
            ذاكرة.مرحلة_الحجز = "انتظار_الخدمة"
            لوحة = ReplyKeyboardMarkup(
                [خدمات_متاحة[:3], خدمات_متاحة[3:6], خدمات_متاحة[6:]],
                resize_keyboard=True, one_time_keyboard=True
            )
            await update.message.reply_text(
                f"بكل سرور {ذاكرة.اسم_المريض}! وش الخدمة اللي تحتاجها؟",
                reply_markup=لوحة
            )
        return

    elif نية == "إلغاء موعد":
        ذاكرة.مرحلة_الحجز = "انتظار_خيار_إلغاء"
        اسم = ذاكرة.اسم_المريض
        لوحة = ReplyKeyboardMarkup(
            [["١. إلغاء نهائي", "٢. تغيير الموعد"]],
            resize_keyboard=True, one_time_keyboard=True
        )
        رد = f"حسناً {اسم}، وش تبي؟" if اسم else "حسناً، وش تبي؟"
        await update.message.reply_text(رد, reply_markup=لوحة)
        return

    رد = رد_البوت(نية, رسالة)
    رد_مخصص = ذاكرة.خصص_الرد(رد, نية)

    # رسالة ترحيب للمريض الجديد
    if معرف not in مرضى_جدد and نية == "ترحيب":
        مرضى_جدد.add(معرف)
        رد_مخصص = "أهلاً بك لأول مرة في عيادة برايت سمايل! يسعدنا خدمتك.\n\n" + رد_مخصص

    # إظهار القائمة الرئيسية عند عدم الفهم
    if نية == "غير معروف":
        await update.message.reply_text(رد_مخصص, reply_markup=القائمة_الرئيسية)
        return

    ذاكرة.ذاكرة.append({'رسالة': رسالة, 'نية': نية, 'رد': رد_مخصص})
    await update.message.reply_text(رد_مخصص, reply_markup=القائمة_الرئيسية)

async def handle_photo(update: Update, context: ContextTypes.DEFAULT_TYPE):
    معرف = update.message.from_user.id
    if معرف not in ذاكرة_المستخدمين:
        ذاكرة_المستخدمين[معرف] = ذاكرة_المحادثة()
    ذاكرة = ذاكرة_المستخدمين[معرف]
    await update.message.reply_text("جاري تحليل الصورة... ⏳")
    صورة = await update.message.photo[-1].get_file()
    await صورة.download_to_drive('temp_image.jpg')
    نتيجة = حلل_الصورة('temp_image.jpg')
    if ذاكرة.اسم_المريض:
        await update.message.reply_text(f"{ذاكرة.اسم_المريض}، {نتيجة}")
    else:
        await update.message.reply_text(نتيجة)

async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    معرف = update.message.from_user.id
    ذاكرة_المستخدمين[معرف] = ذاكرة_المحادثة()
    await update.message.reply_text(
        "أهلاً بك في عيادة برايت سمايل 🦷\n"
        "كيف أقدر أساعدك اليوم؟\n\n"
        "اختر من القائمة أو اكتب سؤالك مباشرة:",
        reply_markup=القائمة_الرئيسية
    )

def main():
    app = Application.builder().token(TOKEN).build()
    app.add_handler(CommandHandler("start", start))
    app.add_handler(MessageHandler(filters.PHOTO, handle_photo))
    app.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND, handle_message))
    if WEBHOOK_URL:
        print("البوت شغال بـ Webhook!")
        app.run_webhook(listen="0.0.0.0", port=PORT, webhook_url=WEBHOOK_URL)
    else:
        print("البوت شغال بـ Polling!")
        app.run_polling()

if __name__ == "__main__":
    main()