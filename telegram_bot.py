def حفظ_حجز(اسم, جوال, يوم, وقت, خدمة="كشف"):
    try:
        data = {"اسم": اسم, "جوال": جوال, "يوم": يوم, "وقت": وقت, "خدمة": خدمة}
        requests.post(SHEET_URL, json=data, timeout=10)
        return True
    except:
        return False

